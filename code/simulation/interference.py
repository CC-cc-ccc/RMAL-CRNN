import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import synthesis as ms
import common as mc
ms.apply_style()
OUT = 'fig_lma_sir'
BETA = mc.BETA_INIT
V = ms.V_NUM
fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.5))
ax = axes[0]
SIR_SHOW = -3.0
rng = np.random.default_rng(20)
lm_logits, dot_logits = ([], [])
for _ in range(60):
    cls = int(rng.integers(ms.NUM_CLASS))
    _, deg = mc.make_pair(cls, rng, 'sir', SIR_SHOW)
    td = mc.view_tokens(deg)
    bp = np.ones(td.shape[1])
    _, lg, _ = ms.logmap_tangent_attention(td, bp, beta=BETA, return_logits=True)
    _, dg, _ = ms.standard_dot_attention(td, return_logits=True)
    off = ~np.eye(td.shape[0], dtype=bool)
    lm_logits.append(lg[off])
    dot_logits.append(dg[off])
lm_logits = np.concatenate(lm_logits)
dot_logits = np.concatenate(dot_logits)
lo_bound = -4.0 * BETA
ax.axvspan(lo_bound, 0.0, color=mc.C_OURS, alpha=0.12, zorder=0, label=f'admissible box  $[-4\\beta,\\,0]=[{lo_bound:.0f},0]$')
yj_lm = 1.0 + 0.1 * rng.standard_normal(lm_logits.size)
yj_dot = 0.0 + 0.1 * rng.standard_normal(dot_logits.size)
ax.scatter(dot_logits, yj_dot, s=5, color=mc.C_STD, alpha=0.35, edgecolors='none', label='dot-product logits (unbounded)')
ax.scatter(lm_logits, yj_lm, s=5, color=mc.C_OURS, alpha=0.5, edgecolors='none', label='log-map logits (bounded)')
ax.axvline(lo_bound, color=mc.C_WARN, lw=1.2, ls='--')
ax.axvline(0.0, color=mc.C_WARN, lw=1.2, ls='--')
ax.set_xscale('symlog', linthresh=2.0)
ax.set_yticks([0, 1])
ax.set_yticklabels(['dot', 'log-map'])
ax.set_ylim(-0.6, 1.6)
ax.set_xlabel('attention logit  (symmetric-log scale),  SIR $=%.0f$ dB' % SIR_SHOW)
ax.set_title('(a)  Bounded-logit containment', loc='left', fontweight='bold')
ax.annotate('dot logits escape\nthe box by orders\nof magnitude', xy=(dot_logits.max(), 0.0), xytext=(0.62, 0.3), textcoords='axes fraction', fontsize=9, color=mc.C_STD, arrowprops=dict(arrowstyle='->', color=mc.C_STD, lw=1.0))
ax.legend(loc='upper left', fontsize=8.0, framealpha=0.95)
ax.grid(alpha=0.4, axis='x')
ax = axes[1]
sir_grid = np.array([18, 12, 8, 4, 0, -3, -6], dtype=float)
fid_lm, fid_dot, mw_lm, mw_dot = ([], [], [], [])
n_tr = 90
for sir in sir_grid:
    fl, fd, ml, md = ([], [], [], [])
    rng = np.random.default_rng(100)
    for _ in range(n_tr):
        cls = int(rng.integers(ms.NUM_CLASS))
        clean, deg = mc.make_pair(cls, rng, 'sir', sir)
        tc, td = (mc.view_tokens(clean), mc.view_tokens(deg))
        bp = np.ones(tc.shape[1])
        A_l_c = ms.logmap_tangent_attention(tc, bp, beta=BETA)
        A_l_d = ms.logmap_tangent_attention(td, bp, beta=BETA)
        A_d_c = ms.standard_dot_attention(tc)
        A_d_d = ms.standard_dot_attention(td)
        fl.append(mc.cosine(mc.fused_repr(td, A_l_d), mc.fused_repr(tc, A_l_c)))
        fd.append(mc.cosine(mc.fused_repr(td, A_d_d), mc.fused_repr(tc, A_d_c)))
        ml.append(mc.max_attention(A_l_d))
        md.append(mc.max_attention(A_d_d))
    fid_lm.append(np.mean(fl))
    fid_dot.append(np.mean(fd))
    mw_lm.append(np.mean(ml))
    mw_dot.append(np.mean(md))
fid_lm = np.array(fid_lm)
fid_dot = np.array(fid_dot)
mw_lm = np.array(mw_lm)
mw_dot = np.array(mw_dot)
ax.fill_between(sir_grid, fid_dot, fid_lm, color=mc.C_OURS, alpha=0.1, zorder=0)
ax.plot(sir_grid, fid_lm, '-o', color=mc.C_OURS, lw=2.4, ms=6, label='log-map attention (ours)')
ax.plot(sir_grid, fid_dot, '-s', color=mc.C_STD, lw=2.2, ms=6, mfc='white', label='dot-product attention')
ax.set_xlabel('SIR  (dB)   $\\longleftarrow$  stronger interference')
ax.set_ylabel('fused-representation fidelity\n$\\cos(\\,O_{\\mathrm{deg}},\\,O_{\\mathrm{clean}}\\,)$')
ax.set_title('(b)  Fusion preserved under interference', loc='left', fontweight='bold')
ax.invert_xaxis()
ax.set_ylim(0.7, 1.01)
cap = mc.lma_maxweight_cap(BETA, V)
txt = f'max attention weight (mean):\n  dot-product $= {mw_dot.mean():.2f}$  (collapse onto 1 view)' + f'\n  log-map $= {mw_lm.mean():.2f}\\ \\leq$ cap ${cap:.2f}$'
ax.text(0.97, 0.05, txt, transform=ax.transAxes, fontsize=8.2, va='bottom', ha='right', bbox=dict(boxstyle='round,pad=0.4', fc='white', ec='#cccccc'))
ax.legend(loc='lower left', fontsize=8.5)
ax.grid(alpha=0.5)
fig.tight_layout()
fig.savefig(OUT + '.pdf', bbox_inches='tight')
fig.savefig(OUT + '.png', bbox_inches='tight', dpi=200)
print('saved', OUT + '.pdf /.png')
print('  -4beta =', lo_bound, ' maxweight cap =', round(mc.lma_maxweight_cap(BETA, V), 3))
print('  log-map logit max = %.3f (<=0?) ' % lm_logits.max(), ' dot logit max = %.1f' % dot_logits.max())
print('  SIR grid          :', list(sir_grid))
print('  fidelity LMA      :', np.round(fid_lm, 3))
print('  fidelity dot      :', np.round(fid_dot, 3))
print('  max-weight LMA/dot: %.2f / %.2f   cap=%.2f' % (mw_lm.mean(), mw_dot.mean(), cap))
